import pandas as pd

from cartrank.data import reviews
from cartrank.data.paths import CATEGORY, PROCESSED, RESULTS

CANDIDATES = ["Office_Products", "Sports_and_Outdoors", "Toys_and_Games"]
LABELS = ["E", "S", "C", "I"]


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def esci_section() -> str:
    d = PROCESSED / "esci"
    splits = {n: pd.read_parquet(d / f"{n}.parquet") for n in ("train", "dev", "test")}
    rows = []
    for name, df in splits.items():
        mix = df.esci_label.value_counts(normalize=True)
        rows.append(
            {
                "split": name,
                "queries": f"{df.query_id.nunique():,}",
                "judgments": f"{len(df):,}",
                "judged/query": f"{len(df) / df.query_id.nunique():.1f}",
                **{k: f"{mix.get(k, 0):.1%}" for k in LABELS},
            }
        )
    all_df = pd.concat(splits.values())
    return (
        "## ESCI (US locale, small_version == 1; Task 1 ranking set)\n\n"
        f"{_md(pd.DataFrame(rows))}\n\n"
        f"Distinct products in the set: {all_df.product_id.nunique():,}. "
        "Dev = 10% of train query_ids (seed 0, split by query). Test is the provided split, "
        "untouched until Phase 7.\n"
    )


def reviews_section() -> str:
    d = PROCESSED / "reviews"
    splits = {n: pd.read_parquet(d / f"{n}.parquet") for n in ("train", "dev", "test")}
    meta = pd.read_parquet(d / "meta.parquet")
    inter = pd.concat(splits.values())
    n_u, n_i = inter.user_id.nunique(), inter.parent_asin.nunique()
    with_price = meta.price.notna().sum()
    rating = inter.rating.value_counts(normalize=True).sort_index()
    train_cnt = splits["train"].parent_asin.value_counts()
    cold = (train_cnt < 5).sum() + (n_i - len(train_cnt))
    out = [
        f"## Amazon Reviews 2023: {CATEGORY} (5-core, after leave-last-out filtering)\n",
        _md(
            pd.DataFrame(
                [
                    {
                        "users": f"{n_u:,}",
                        "items": f"{n_i:,}",
                        "interactions": f"{len(inter):,}",
                        "sparsity": f"{1 - len(inter) / (n_u * n_i):.5f}",
                        "train / dev / test": " / ".join(f"{len(s):,}" for s in splits.values()),
                    }
                ]
            )
        ),
        "",
        f"Price coverage: {with_price:,} of {len(meta):,} catalog items have a non-null price "
        f"({with_price / len(meta):.1%}).",
        f"Items with fewer than 5 train interactions (cold-start slice): {cold:,} "
        f"({cold / n_i:.1%}).\n",
        "Rating distribution (interactions):\n",
        _md(pd.DataFrame({"rating": rating.index, "share": [f"{v:.1%}" for v in rating]})),
        "",
    ]
    return "\n".join(out)


def candidates_section() -> str:
    rows = []
    for c in CANDIDATES:
        a = reviews.load_interactions(c)
        rows.append(
            {
                "category": c,
                "users": f"{a.user_id.nunique():,}",
                "items": f"{a.parent_asin.nunique():,}",
                "interactions": f"{len(a):,}",
                "fits (<=150K items, <=2M inter.)": (
                    "yes" if a.parent_asin.nunique() <= 150_000 and len(a) <= 2_000_000 else "no"
                ),
            }
        )
    return (
        "## Category candidates (official 5-core last_out benchmark)\n\n"
        f"{_md(pd.DataFrame(rows))}\n\n"
        "Electronics and Home_and_Kitchen were excluded without full counting: their 5-core "
        "train files are 707 MB and 1,297 MB vs 79 MB for Office_Products.\n"
    )


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    text = "# Data profile\n\nGenerated by `python -m cartrank.data.profile`.\n\n"
    text += "\n".join([esci_section(), reviews_section(), candidates_section()])
    (RESULTS / "data_profile.md").write_text(text)


if __name__ == "__main__":
    main()
